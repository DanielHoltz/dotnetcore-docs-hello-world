import re,unicodedata
SAIS=r'(CLORIDRATO|DICLORIDRATO|BROMIDRATO|IODIDRATO|MALEATO|DIMALEATO|SUCCINATO|TARTARATO|HEMITARTARATO|BITARTARATO|FUMARATO|HEMIFUMARATO|MESILATO|DIMESILATO|BESILATO|BENZOATO|CITRATO|DICITRATO|ACETATO|DIACETATO|LACTATO|GLUCONATO|NITRATO|FOSFATO|DIFOSFATO|FOSFATO SÓDICO|SULFATO|BISSULFATO|HIDROGENOSSULFATO|CANSILATO|TOSILATO|ESILATO|ISETIONATO|OXALATO|PAMOATO|EMBONATO|ESTEARATO|PROPIONATO|DIPROPIONATO|VALERATO|BUTIRATO|FUROATO|XINAFOATO|TROMETAMOL|BROMETO|IODETO|CLORETO|SAL SÓDICO|DIIDRATO|MONOIDRATO)'
MINERAIS=r'(SÓDIO|POTÁSSIO|CÁLCIO|MAGNÉSIO|FERRO|ZINCO|LÍTIO|ALUMÍNIO|AMÔNIO|PRATA|BÁRIO|COBRE|SELÊNIO|CROMO|MANGANÊS|ESTRÔNCIO|BISMUTO|OURO|SUXAMETÔNIO|ROCURÔNIO|VECURÔNIO|PANCURÔNIO|ATRACÚRIO|CISATRACÚRIO|IPRATRÓPIO|TIOTRÓPIO|ESCOPOLAMINA|BUTILBROMETO|PIRIDOSTIGMINA|NEOSTIGMINA|BENZALCÔNIO|CETILPIRIDÍNIO|OXIBUTININA|FÉRRICO|FERROSO)'
HID=r'\b(MONOIDRATADO|MONOIDRATADA|DI-?HIDRATADO|DI-?HIDRATADA|DIIDRATADO|DIIDRATADA|TRI-?HIDRATADO|TRI-?HIDRATADA|TRIIDRATADO|TRIIDRATADA|SESQUI-?HIDRATADO|SESQUI-?HIDRATADA|SESQUIIDRATADO|HEMI-?HIDRATADO|HEMI-?HIDRATADA|HEMIIDRATADO|HEMIIDRATADA|PENTAIDRATADO|PENTA-?HIDRATADO|HEPTAIDRATADO|HEXAIDRATADO|TETRAIDRATADO|ANIDRO|ANIDRA|HIDRATADO|HIDRATADA|MICRONIZADO|MICRONIZADA|AMORFO|AMORFA|CRISTALINO|ULTRAMICRONIZADO)\b'
ADJ=r'\s(SÓDICO|SÓDICA|DISSÓDICO|DISSÓDICA|POTÁSSICO|POTÁSSICA|CÁLCICO|CÁLCICA|MAGNÉSICO|MAGNÉSICA|DE SÓDIO|DE POTÁSSIO|DE CÁLCIO|DE MAGNÉSIO|BENZATINA|PROCAÍNA|ARGININA|LISINA|DE LISINA|MEGLUMINA|DE MEGLUMINA|TROMETAMOL|TROMETAMINA|HICLATO|MONOSSÓDICO|TRISSÓDICO|DE ZINCO|BASE)$'
def base1(s):
    s=re.sub(r'\s+',' ',s.strip().upper())
    s=re.sub(HID,'',s); s=re.sub(r'\s+',' ',s).strip()
    m=re.match(SAIS+r'\s+DE\s+(.+)$',s)
    if m and not re.search(MINERAIS,m.group(2)) and not re.match(r'^(SÓDIO|POTÁSSIO|CÁLCIO|MAGNÉSIO)',m.group(2)):
        s=m.group(2)
    for _ in range(2):
        t=re.sub(ADJ,'',s)
        if t!=s and len(t)>3 and not re.search(r'^(CLORETO|BICARBONATO|GLUCONATO|SULFATO|FOSFATO|CITRATO|ACETATO|LACTATO|CARBONATO|HIDRÓXIDO|ÓXIDO|IODETO)\b',t): s=t
    s=re.sub(r'^\d+-','',s)  # 21-ACETATO...
    s=re.sub(r'^TROMETAMOL\s+','',s)  # TROMETAMOL CETOROLACO -> CETOROLACO
    return s.strip(' ,')
def base(sub):
    partes=[base1(p) for p in sub.split(';') if p.strip()]
    partes=sorted(set(partes))
    return ' + '.join(partes)
def titulo(s):
    pequenas={'DE','DA','DO','DAS','DOS','E','EM','COM','A','O','AS','OS','À','PARA','POR','NA','NO'}
    out=[]
    for i,w in enumerate(s.lower().split(' ')):
        out.append(w if (w.upper() in pequenas and i>0) else w[:1].upper()+w[1:])
    t=' '.join(out)
    t=re.sub(r'(\+ )([a-zà-ú])',lambda m:m.group(1)+m.group(2).upper(),t)
    return t
def chave(s):
    return re.sub(r'[^a-z0-9]','',unicodedata.normalize('NFD',s.lower()).encode('ascii','ignore').decode())
